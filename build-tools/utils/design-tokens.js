const fs = require('node:fs/promises');
const path = require('node:path');
const { rootDir, toKebabCase } = require('./index');

const outDir = path.join(rootDir, 'lib/design-tokens');
const license = ['// Copyright Christopher Johnson. All Rights Reserved.', '// SPDX-License-Identifier: Apache-2.0'];
const header = '// Generated by build-tools/tasks/style-dictionary.js. Do not edit.';

const cssReference = name => `var(--ord-${toKebabCase(name)})`;

function renderJs(tokenNames) {
  const lines = tokenNames.map(name => `export const ${name} = '${cssReference(name)}';`);
  return [...license, header, ...lines, ''].join('\n');
}

function renderTypes(tokenNames) {
  const lines = tokenNames.map(name => `export declare const ${name}: '${cssReference(name)}';`);
  return [...license, header, ...lines, ''].join('\n');
}

// The same names as the internal `ord.$...` variables, so styles move between the two unchanged.
function renderScss(tokenNames) {
  const lines = tokenNames.map(name => `$${toKebabCase(name)}: ${cssReference(name)};`);
  return [...license, header, ...lines, ''].join('\n');
}

function renderManifest(source) {
  const manifest = {
    name: '@ordinate/design-tokens',
    version: source.version,
    description: 'Ordinate design tokens as CSS custom property references, for JavaScript and Sass.',
    license: source.license,
    repository: source.repository,
    type: 'module',
    main: './index.js',
    types: './index.d.ts',
    sass: './index.scss',
    exports: {
      '.': { types: './index.d.ts', sass: './index.scss', default: './index.js' },
      './index.scss': './index.scss',
      './package.json': './package.json',
    },
    sideEffects: false,
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/**
 * Writes the `@ordinate/design-tokens` package: every token as a reference to its CSS custom
 * property, which the revision styles shipped with the components define.
 */
async function writeDesignTokens(tokenNames) {
  const source = JSON.parse(await fs.readFile(path.join(rootDir, 'package.json'), 'utf8'));
  await fs.mkdir(outDir, { recursive: true });
  await Promise.all([
    fs.writeFile(path.join(outDir, 'index.js'), renderJs(tokenNames)),
    fs.writeFile(path.join(outDir, 'index.d.ts'), renderTypes(tokenNames)),
    fs.writeFile(path.join(outDir, 'index.scss'), renderScss(tokenNames)),
    fs.writeFile(path.join(outDir, 'package.json'), renderManifest(source)),
    ...['LICENSE', 'NOTICE'].map(file => fs.copyFile(path.join(rootDir, file), path.join(outDir, file))),
  ]);
}

module.exports = { writeDesignTokens };
