const fs = require('node:fs/promises');
const path = require('node:path');
const { rootDir, task, tsc, toKebabCase } = require('../utils');
const { writeDesignTokens } = require('../utils/design-tokens');

const outputDir = path.join(rootDir, 'src/internal/generated/styles');
const themingDir = path.join(rootDir, 'src/internal/generated/theming');
const header = '// Generated by build-tools/tasks/style-dictionary.js. Do not edit.\n';
const compactClassName = 'ord-compact-mode';

const cssVariable = name => `--ord-${toKebabCase(name)}`;
const revisionClassName = id => `ord-revision-${id.replace(/\./g, '-')}`;

const isDensityValue = value => typeof value === 'object' && 'comfortable' in value;

function declaration(name, value) {
  const variable = cssVariable(name);
  if (typeof value === 'string') {
    return [`  ${variable}: ${value};`];
  }
  if (isDensityValue(value)) {
    // Both values travel with the revision; the density class only picks one.
    return [
      `  ${variable}-comfortable: ${value.comfortable};`,
      `  ${variable}-compact: ${value.compact};`,
      `  ${variable}: var(${variable}-comfortable);`,
    ];
  }
  return [`  ${variable}: light-dark(${value.light}, ${value.dark});`];
}

function declarations(resolved) {
  return Object.entries(resolved)
    .flatMap(([name, value]) => declaration(name, value))
    .join('\n');
}

function renderDensity(revisions, resolveTokens) {
  const names = new Set();
  for (const revision of revisions) {
    for (const [name, value] of Object.entries(resolveTokens(revision.tokens))) {
      if (isDensityValue(value)) {
        names.add(name);
      }
    }
  }
  const revisionSelectors = revisions.map(revision => `.${revisionClassName(revision.id)}`).join(', ');
  const lines = [...names].map(name => `  ${cssVariable(name)}: var(${cssVariable(name)}-compact);`);
  // The second selector catches revision subtrees inside a compact area, which would otherwise
  // reset the variables to their comfortable values.
  const selectors = [`:global(.${compactClassName})`, `:global(.${compactClassName} :is(${revisionSelectors}))`];
  return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`;
}

function renderRevisions(revisions, resolveTokens, styles, allTokenNames) {
  const [defaultRevision] = revisions;
  const blocks = revisions.map(revision => {
    const selectors = [`:global(.${revisionClassName(revision.id)})`];
    if (revision === defaultRevision) {
      selectors.unshift(':global(:root)');
    }
    return `${selectors.join(',\n')} {\n${declarations(resolveTokens(revision.tokens))}\n}\n`;
  });
  return [
    header,
    ':global(:root),\n:global(.ord-light-mode) {\n  color-scheme: light;\n}\n',
    ':global(.ord-dark-mode) {\n  color-scheme: dark;\n}\n',
    ':global(.ord-system-mode) {\n  color-scheme: light dark;\n}\n',
    ...blocks,
    renderDensity(revisions, resolveTokens),
    renderStyles(styles, revisions, allTokenNames),
  ].join('\n');
}

const referencePattern = /^\{([a-zA-Z0-9]+)\}$/;

// Style values stay live: a reference becomes the referenced variable, so a style follows
// whichever revision and mode it sits in.
function styleValue(value) {
  const live = part => {
    const match = referencePattern.exec(part);
    return match ? `var(${cssVariable(match[1])})` : part;
  };
  return typeof value === 'string' ? live(value) : `light-dark(${live(value.light)}, ${live(value.dark)})`;
}

function renderStyles(styles, revisions, allTokenNames) {
  const known = new Set(allTokenNames);
  const revisionSelectors = revisions.map(revision => `.${revisionClassName(revision.id)}`).join(', ');
  return styles
    .map(style => {
      const lines = Object.entries(style.overrides).map(([name, value]) => {
        if (!known.has(name)) {
          throw new Error(`Style "${style.id}" overrides unknown token "${name}".`);
        }
        return `  ${cssVariable(name)}: ${styleValue(value)};`;
      });
      // The second selector reaches revision subtrees inside a styled area, which would
      // otherwise reset the tokens to the revision's values.
      const className = `ord-style-${style.id}`;
      const selectors = [`:global(.${className})`, `:global(.${className} :is(${revisionSelectors}))`];
      return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`;
    })
    .join('\n');
}

function renderTheming(revisions, themeableTokenNames) {
  const tokens = themeableTokenNames.map(name => `  ${name}: '${cssVariable(name)}',`);
  const classNames = revisions.map(revision => `  '${revisionClassName(revision.id)}',`);
  return [
    '// Copyright Christopher Johnson. All Rights Reserved.',
    '// SPDX-License-Identifier: Apache-2.0',
    header,
    `export const themeableTokens = {\n${tokens.join('\n')}\n} as const;\n`,
    'export type ThemeableTokenName = keyof typeof themeableTokens;\n',
    `export const revisionClassNames = [\n${classNames.join('\n')}\n] as const;\n`,
  ].join('\n');
}

function renderTokens(tokenNames) {
  const lines = tokenNames.map(name => `$${toKebabCase(name)}: var(${cssVariable(name)});`);
  return `${header}\n${lines.join('\n')}\n`;
}

module.exports = task('style-dictionary', async () => {
  await tsc('tsconfig.style-dictionary.json');
  const entry = path.join(rootDir, 'lib/style-dictionary/index.js');
  for (const cached of Object.keys(require.cache)) {
    if (cached.startsWith(path.dirname(entry))) {
      delete require.cache[cached];
    }
  }
  const { revisions, styles, resolveTokens, allTokenNames, themeableTokenNames } = require(entry);

  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(
    path.join(outputDir, 'revisions.scss'),
    renderRevisions(revisions, resolveTokens, styles, allTokenNames)
  );
  await fs.writeFile(path.join(outputDir, 'tokens.scss'), renderTokens(allTokenNames));
  await fs.mkdir(themingDir, { recursive: true });
  await fs.writeFile(path.join(themingDir, 'index.ts'), renderTheming(revisions, themeableTokenNames));
  await writeDesignTokens(allTokenNames);
});
