const fs = require('node:fs/promises');
const path = require('node:path');
const { rootDir, task, tsc, toKebabCase } = require('../utils');

const outputDir = path.join(rootDir, 'src/internal/generated/styles');
const header = '// Generated by build-tools/tasks/style-dictionary.js. Do not edit.\n';

const cssVariable = name => `--ord-${toKebabCase(name)}`;
const revisionClassName = id => `ord-revision-${id.replace(/\./g, '-')}`;

function formatValue(value) {
  return typeof value === 'string' ? value : `light-dark(${value.light}, ${value.dark})`;
}

function declarations(resolved) {
  return Object.entries(resolved)
    .map(([name, value]) => `  ${cssVariable(name)}: ${formatValue(value)};`)
    .join('\n');
}

function renderRevisions(revisions, resolveTokens) {
  const [defaultRevision] = revisions;
  const blocks = revisions.map(revision => {
    const selectors = [`:global(.${revisionClassName(revision.id)})`];
    if (revision === defaultRevision) {
      selectors.unshift(':global(:root)');
    }
    return `${selectors.join(',\n')} {\n${declarations(resolveTokens(revision.tokens))}\n}\n`;
  });
  return [
    header,
    ':global(:root),\n:global(.ord-light-mode) {\n  color-scheme: light;\n}\n',
    ':global(.ord-dark-mode) {\n  color-scheme: dark;\n}\n',
    ':global(.ord-system-mode) {\n  color-scheme: light dark;\n}\n',
    ...blocks,
  ].join('\n');
}

function renderTokens(tokenNames) {
  const lines = tokenNames.map(name => `$${toKebabCase(name)}: var(${cssVariable(name)});`);
  return `${header}\n${lines.join('\n')}\n`;
}

module.exports = task('style-dictionary', async () => {
  await tsc('tsconfig.style-dictionary.json');
  const entry = path.join(rootDir, 'lib/style-dictionary/index.js');
  for (const cached of Object.keys(require.cache)) {
    if (cached.startsWith(path.dirname(entry))) {
      delete require.cache[cached];
    }
  }
  const { revisions, resolveTokens, allTokenNames } = require(entry);

  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(path.join(outputDir, 'revisions.scss'), renderRevisions(revisions, resolveTokens));
  await fs.writeFile(path.join(outputDir, 'tokens.scss'), renderTokens(allTokenNames));
});
