const fs = require('node:fs/promises');
const path = require('node:path');
const { rootDir, task, toPascalCase } = require('../utils');

const domDir = path.join(rootDir, 'src/test-utils/dom');

function pluralize(name) {
  if (/(s|x|ch|sh)$/.test(name)) {
    return `${name}es`;
  }
  if (/[^aeiou]y$/.test(name)) {
    return `${name.slice(0, -1)}ies`;
  }
  return `${name}s`;
}

async function listWrappers() {
  const entries = await fs.readdir(domDir, { withFileTypes: true });
  const names = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }
    const hasIndex = await fs
      .access(path.join(domDir, entry.name, 'index.ts'))
      .then(() => true)
      .catch(() => false);
    if (hasIndex) {
      names.push(entry.name);
    }
  }
  return names.sort();
}

// Every wrapper inherits the generated finders. When a wrapper declares a finder with
// the same name but a different return type (ModalWrapper.findHeader returns the
// modal's header slot, not a Header), that finder cannot go on ElementWrapper and is
// added only to the root wrapper that createWrapper() returns.
async function listOwnMethods(names) {
  const methods = new Map();
  for (const name of names) {
    const source = await fs.readFile(path.join(domDir, name, 'index.ts'), 'utf8');
    for (const match of source.matchAll(/^\s+(find\w+)\s*\([^)]*\)\s*:\s*([^{]+?)\s*\{/gm)) {
      const returns = methods.get(match[1]) ?? new Set();
      returns.add(match[2].replace(/\s+/g, ' '));
      methods.set(match[1], returns);
    }
  }
  return methods;
}

function clashes(ownMethods, finder) {
  const returns = ownMethods.get(finder.method);
  return Boolean(returns) && [...returns].some(type => type !== finder.returns);
}

module.exports = task('generate-test-utils', async () => {
  const names = await listWrappers();
  const ownMethods = await listOwnMethods(names);
  const wrappers = names.map(name => {
    const component = toPascalCase(name);
    return { name, component, wrapper: `${component}Wrapper`, plural: pluralize(component) };
  });
  const finders = wrappers.flatMap(w => [
    { method: `find${w.component}`, returns: `${w.wrapper} | null`, helper: 'findComponent', wrapper: w.wrapper },
    { method: `findAll${w.plural}`, returns: `${w.wrapper}[]`, helper: 'findAllComponents', wrapper: w.wrapper },
  ]);
  const shared = finders.filter(f => !clashes(ownMethods, f));
  const rootOnly = finders.filter(f => clashes(ownMethods, f));

  const content = [
    '// Copyright Christopher Johnson. All Rights Reserved.',
    '// SPDX-License-Identifier: Apache-2.0',
    '// Generated by build-tools/tasks/generate-test-utils.js. Do not edit.',
    "import { ComponentWrapper, ElementWrapper } from './core';",
    ...wrappers.map(w => `import ${w.wrapper} from './${w.name}';`),
    '',
    `export { ComponentWrapper, ElementWrapper, ${wrappers.map(w => w.wrapper).join(', ')} };`,
    '',
    "declare module './core' {",
    '  interface ElementWrapper<E extends Element = HTMLElement> {',
    ...shared.map(f => `    ${f.method}(selector?: string): ${f.returns};`),
    '  }',
    '}',
    '',
    ...shared.flatMap(f => [
      `ElementWrapper.prototype.${f.method} = function (this: ElementWrapper<Element>, selector?: string) {`,
      `  return this.${f.helper}(${f.wrapper}, selector);`,
      '};',
    ]),
    '',
    'export class RootWrapper extends ElementWrapper<Element> {',
    ...rootOnly.flatMap(f => [
      `  ${f.method}(selector?: string): ${f.returns} {`,
      `    return this.${f.helper}(${f.wrapper}, selector);`,
      '  }',
    ]),
    '}',
    '',
    '/**',
    ' * Wraps `root` (the document body by default) so components inside it can be',
    ' * found and driven in tests: `createWrapper().findButton()!.click()`.',
    ' */',
    'export default function createWrapper(root: Element = document.body): RootWrapper {',
    '  return new RootWrapper(root);',
    '}',
    '',
  ].join('\n');

  await fs.writeFile(path.join(domDir, 'index.ts'), content);
});
