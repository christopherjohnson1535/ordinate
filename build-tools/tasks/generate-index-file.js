const fs = require('node:fs/promises');
const path = require('node:path');
const { rootDir, task, toPascalCase } = require('../utils');

const srcDir = path.join(rootDir, 'src');

// Folders with an index.tsx that are not components, exported by hand below.
const nonComponents = new Set(['internal', 'i18n']);
const platformExports = [
  "export { default as I18nProvider } from './i18n';",
  "export type { I18nProviderProps } from './i18n';",
];

async function listComponents() {
  const entries = await fs.readdir(srcDir, { withFileTypes: true });
  const components = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || nonComponents.has(entry.name) || entry.name.startsWith('__')) {
      continue;
    }
    const hasIndex = await fs
      .access(path.join(srcDir, entry.name, 'index.tsx'))
      .then(() => true)
      .catch(() => false);
    if (hasIndex) {
      components.push(entry.name);
    }
  }
  return components.sort();
}

module.exports = task('generate-index-file', async () => {
  const components = await listComponents();
  const lines = components.flatMap(name => {
    const pascal = toPascalCase(name);
    return [`export { default as ${pascal} } from './${name}';`, `export type { ${pascal}Props } from './${name}';`];
  });
  const content = [
    '// Copyright Christopher Johnson. All Rights Reserved.',
    '// SPDX-License-Identifier: Apache-2.0',
    '// Generated by build-tools/tasks/generate-index-file.js. Do not edit.',
    ...lines,
    ...platformExports,
    '',
  ].join('\n');
  await fs.writeFile(path.join(srcDir, 'index.ts'), content);
});
