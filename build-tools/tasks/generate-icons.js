const fs = require('node:fs/promises');
const path = require('node:path');
const { rootDir, task } = require('../utils');

const iconsDir = path.join(rootDir, 'src/icon/icons');
const outputDir = path.join(rootDir, 'src/icon/generated');

function normalize(name, source) {
  const svg = source
    .replace(/<\?xml[^>]*>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
  if (!svg.startsWith('<svg') || !svg.includes('viewBox="0 0 16 16"')) {
    throw new Error(`Icon "${name}" must be an <svg> with viewBox="0 0 16 16".`);
  }
  if (/<script|<style|style=|\son[a-z]+=|xlink:href|\shref=/i.test(svg)) {
    throw new Error(`Icon "${name}" may not contain scripts, styles, event handlers or links.`);
  }
  return svg.includes('focusable=') ? svg : svg.replace('<svg', '<svg focusable="false"');
}

module.exports = task('generate-icons', async () => {
  const files = (await fs.readdir(iconsDir)).filter(file => file.endsWith('.svg')).sort();
  const entries = await Promise.all(
    files.map(async file => {
      const name = path.basename(file, '.svg');
      return [name, normalize(name, await fs.readFile(path.join(iconsDir, file), 'utf8'))];
    })
  );
  const content = [
    '// Generated by build-tools/tasks/generate-icons.js. Do not edit.',
    `export type IconName = ${entries.map(([name]) => `'${name}'`).join(' | ')};`,
    '',
    'const icons: Record<IconName, string> = {',
    ...entries.map(([name, svg]) => `  '${name}': ${JSON.stringify(svg)},`),
    '};',
    '',
    'export default icons;',
    '',
  ].join('\n');
  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(path.join(outputDir, 'icons.ts'), content);
});
